package cc.seebrook.shared.api

import kotlinx.serialization.Serializable

/** Asks for the fee and total of paying [amountCents] of dues, per accepted method (ED-43). */
@Serializable
data class PaymentQuoteRequest(val amountCents: Long)

/** `method` is `card` or `ach`. The fee is what the owner pays on top of the dues; 0 when the HOA absorbs it. */
@Serializable
data class PaymentOptionResponse(val method: String, val feeCents: Long, val totalCents: Long)

/** Every figure is computed by the backend; the app shows them and the owner approves one option. */
@Serializable
data class PaymentQuoteResponse(
    val propertyId: String,
    val currency: String,
    val amountCents: Long,
    /** What the owner owes now, as a suggestion; any amount from $1 may be paid. */
    val amountDueCents: Long,
    val options: List<PaymentOptionResponse>,
)

/**
 * Starts a payment for exactly the approved option. [idempotencyKey] is generated by the app once
 * per approval (e.g. a UUID) and sent again on retry, so a repeated tap never pays twice.
 */
@Serializable
data class StartPaymentRequest(
    val method: String,
    val amountCents: Long,
    val feeCents: Long,
    val totalCents: Long,
    val idempotencyKey: String,
)

/**
 * A payment. `status` is created, processing, succeeded, failed or canceled. [provider] and
 * [clientParams] are for the provider's own SDK, which collects the card or bank details (X-02);
 * [clientParams] is present only while the owner still has to complete the payment.
 */
@Serializable
data class PaymentResponse(
    val id: String,
    val reference: String,
    val status: String,
    val method: String,
    val amountCents: Long,
    val feeCents: Long,
    val totalCents: Long,
    val currency: String,
    val createdAt: String,
    val succeededAt: String? = null,
    /** The provider's code, for support; show [failureMessage] to the owner. */
    val failureReason: String? = null,
    /** Why it failed, in words for the owner (ED-64). */
    val failureMessage: String? = null,
    val provider: String? = null,
    val clientParams: Map<String, String>? = null,
)

@Serializable
data class PaymentsResponse(val payments: List<PaymentResponse>)

/** Answer to a start request whose fee or total changed: nothing was charged; reconfirm this quote. */
@Serializable
data class QuoteChangedResponse(val error: String, val quote: PaymentQuoteResponse)
